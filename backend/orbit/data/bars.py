"""Daily bar types, validation, split adjustment and data-quality reporting.

Data modes are kept visibly separate:
- SAMPLE: offline synthetic prices generated by Orbit. Never real. Orders disabled.
- CSV_IMPORT: user-supplied historical file, documented provenance.
- ALPACA: fetched from Alpaca market data (feed recorded, e.g. IEX).
- MOCK: deterministic fixture data used only with the in-memory MockBroker (tests / mock demo).
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from datetime import date
from decimal import Decimal

from orbit.market_calendar import MarketCalendar
from orbit.money import D

DATA_MODES = {"SAMPLE", "CSV_IMPORT", "ALPACA", "MOCK"}


@dataclass(frozen=True)
class Bar:
    day: date
    open: Decimal
    high: Decimal
    low: Decimal
    close: Decimal
    volume: Decimal = Decimal(0)


@dataclass(frozen=True)
class SplitEvent:
    ex_date: date
    ratio: Decimal  # new shares per old share, e.g. 4 for a 4-for-1 split


@dataclass
class BarSeries:
    symbol: str
    mode: str
    source: str
    price_basis: str  # "raw" | "split_adjusted"
    bars: list[Bar]
    splits: list[SplitEvent] = field(default_factory=list)
    dividends_included: bool = False
    metadata: dict = field(default_factory=dict)

    def __post_init__(self):
        if self.mode not in DATA_MODES:
            raise ValueError(f"unknown data mode {self.mode}")

    def fingerprint(self) -> str:
        h = hashlib.sha256()
        h.update(f"{self.symbol}|{self.mode}|{self.source}|{self.price_basis}".encode())
        for b in self.bars:
            h.update(f"{b.day}|{b.open}|{b.high}|{b.low}|{b.close}".encode())
        for s in self.splits:
            h.update(f"split|{s.ex_date}|{s.ratio}".encode())
        return h.hexdigest()[:16]

    def describe(self) -> dict:
        return {
            "symbol": self.symbol,
            "mode": self.mode,
            "source": self.source,
            "price_basis": self.price_basis,
            "dividends_included": self.dividends_included,
            "first_session": self.bars[0].day.isoformat() if self.bars else None,
            "last_session": self.bars[-1].day.isoformat() if self.bars else None,
            "bar_count": len(self.bars),
            "splits": [{"ex_date": s.ex_date.isoformat(), "ratio": str(s.ratio)} for s in self.splits],
            "fingerprint": self.fingerprint(),
            "metadata": self.metadata,
        }


class DataQualityError(ValueError):
    pass


def validate_bars(bars: list[Bar], calendar: MarketCalendar | None = None) -> dict:
    """Check ordering, duplicates, positive finite prices, OHLC consistency and calendar gaps.

    Raises DataQualityError for problems that make the data unusable (duplicates,
    non-positive prices, unordered rows, non-session dates). Missing sessions are
    reported but preserved as gaps rather than invented.
    """
    issues: list[str] = []
    seen: set[date] = set()
    prev: date | None = None
    for b in bars:
        if b.day in seen:
            raise DataQualityError(f"duplicate bar for {b.day}")
        seen.add(b.day)
        if prev and b.day <= prev:
            raise DataQualityError(f"bars out of order at {b.day}")
        prev = b.day
        for name in ("open", "high", "low", "close"):
            v = getattr(b, name)
            if not isinstance(v, Decimal) or not v.is_finite() or v <= 0:
                raise DataQualityError(f"non-positive or non-finite {name} on {b.day}")
        if b.high < max(b.open, b.close, b.low) or b.low > min(b.open, b.close, b.high):
            raise DataQualityError(f"inconsistent OHLC on {b.day}")
        if calendar is not None and calendar.sessions and calendar.sessions[0].day <= b.day <= calendar.sessions[-1].day:
            if not calendar.is_session(b.day):
                raise DataQualityError(f"{b.day} is not an exchange session (weekend/holiday bar)")
    missing: list[str] = []
    if calendar is not None and bars:
        for s in calendar.sessions_between(bars[0].day, bars[-1].day):
            if s.day not in seen:
                missing.append(s.day.isoformat())
    if missing:
        issues.append(f"{len(missing)} missing session(s); gaps preserved, not filled")
    return {"ok": True, "missing_sessions": missing, "issues": issues, "count": len(bars)}


def split_adjust(bars: list[Bar], splits: list[SplitEvent]) -> list[Bar]:
    """Backward-adjust raw prices for splits so the series is continuous at the latest share basis."""
    if not splits:
        return list(bars)
    out = []
    for b in bars:
        factor = Decimal(1)
        for s in splits:
            if b.day < s.ex_date:
                factor *= D(s.ratio)
        if factor == 1:
            out.append(b)
        else:
            out.append(Bar(b.day, b.open / factor, b.high / factor, b.low / factor, b.close / factor, b.volume * factor))
    return out


def bars_to_json(bars: list[Bar]) -> str:
    return json.dumps(
        [[b.day.isoformat(), str(b.open), str(b.high), str(b.low), str(b.close), str(b.volume)] for b in bars]
    )


def bars_from_json(s: str) -> list[Bar]:
    return [Bar(date.fromisoformat(r[0]), D(r[1]), D(r[2]), D(r[3]), D(r[4]), D(r[5])) for r in json.loads(s)]
