# Runs the automated checks and writes docs\TEST_EVIDENCE.md with the real output.
. "$PSScriptRoot\_common.ps1"
$ErrorActionPreference = "Continue"
$ev = Join-Path $Root "docs\TEST_EVIDENCE.md"
$fence = '```'

Push-Location $Backend
$py = (& uv run --frozen pytest -p no:warnings -rA 2>&1 | Out-String); $pyCode = $LASTEXITCODE
$audit = (& uv run --frozen pip-audit --progress-spinner off 2>&1 | Out-String); $auditCode = $LASTEXITCODE
Pop-Location

Push-Location $Frontend
$tsc = (& npx tsc -b 2>&1 | Out-String); $tscCode = $LASTEXITCODE
$npmAudit = (& npm audit --omit=dev 2>&1 | Out-String)
Pop-Location

# Simple secret scan over source files (not a replacement for a dedicated scanner such as gitleaks).
$files = Get-ChildItem -Path $Root -Recurse -File -Include *.py, *.ts, *.tsx, *.ps1, *.md, *.json, *.toml, *.yml, *.example, Dockerfile -ErrorAction SilentlyContinue |
  Where-Object { $_.FullName -notmatch 'node_modules|\\\.venv\\|\\dist\\|\\data\\|package-lock|uv\.lock' }
$hits = $files | Select-String -Pattern '\b(PK|AK)[A-Z0-9]{16,}\b' | Where-Object { $_.Line -notmatch 'PKTESTKEYVALUE|PKABCDEFGHIJ|PKOFFLINETESTKEY' }
$scan = if ($hits) { "Potential secrets found:`n" + ($hits | Out-String) } else { "No key-like strings found outside known test fixtures ($($files.Count) files scanned)." }

$summary = ($py -split "`n" | Where-Object { $_ -match '^(PASSED|FAILED|ERROR)|passed|failed' }) -join "`n"
$stamp = (Get-Date).ToUniversalTime().ToString("yyyy-MM-dd HH:mm:ss 'UTC'")
$body = @(
  "# Test evidence",
  "",
  "Generated by scripts\test.ps1 at $stamp. This file is overwritten on every run.",
  "",
  "## pytest (exit code $pyCode)",
  $fence, $summary.Trim(), $fence,
  "",
  "## pip-audit: Python dependency vulnerabilities (exit code $auditCode)",
  $fence, $audit.Trim(), $fence,
  "",
  "## TypeScript typecheck (exit code $tscCode)",
  $fence, ($(if ($tsc.Trim()) { $tsc.Trim() } else { "no type errors" })), $fence,
  "",
  "## npm audit (production dependencies)",
  $fence, $npmAudit.Trim(), $fence,
  "",
  "## Secret scan",
  $scan
) -join "`n"
Set-Content -Path $ev -Value $body -Encoding utf8
Write-Host "Wrote $ev  (pytest exit $pyCode, pip-audit exit $auditCode, tsc exit $tscCode)"
exit $pyCode
